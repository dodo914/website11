const mongoose = require('mongoose');

// ============================================================
// ===== عداد أرقام الأوردرات المتسلسلة (Order Numbers) =====
// بيستخدم عشان نديّ كل أوردر رقم متسلسل بسيط (1001، 1002، 1003...)
// بدل الاعتماد على Mongo ObjectId اللي مش متسلسل ومش سهل يتقال للعميل.
// _id هنا هو اسم العداد (زي 'orderNumber') عشان لو احتجنا عدادات تانية
// في المستقبل (زي أرقام فواتير مثلاً) نقدر نضيفها بنفس الموديل.
// seq بيبدأ من 1000 (default)، وأول عملية $inc بتخليه 1001 - ده بالظبط
// المطلوب: أول أوردر رقمه 1001 وبعدين بيمشي بالترتيب (1002، 1003...).
// ============================================================
const counterSchema = new mongoose.Schema({
  _id: { type: String, required: true },
  seq: { type: Number, default: 1000 },
});

module.exports = mongoose.model('Counter', counterSchema);